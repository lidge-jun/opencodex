/** Generate the offline update root from the already-pinned Tauri public key. */
import { readFileSync, renameSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { decodePublicKey } from "../src/update/minisign.mjs";

const repo = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const configPath = resolve(repo, "desktop/src-tauri/tauri.conf.json");
const rootOutputs = [
  resolve(repo, "src/update/trust-root.json"),
  resolve(repo, "desktop/src-tauri/update-trust-root.json"),
];
const channels = ["latest", "preview", "nightly"];
const roles = ["release", "tree", "desktop-artifact", "standalone-artifact", "guardian-artifact"];

export function generateUpdateTrustRoot(config: unknown): string {
  const box = (config as { plugins?: { updater?: { pubkey?: unknown } } })?.plugins?.updater?.pubkey;
  if (typeof box !== "string" || !box || box.length > 4096) throw new Error("Invalid pinned updater public key");
  const encoded = Buffer.from(box, "base64");
  if (encoded.toString("base64") !== box) throw new Error("Updater public key must be canonical base64");
  const text = new TextDecoder("utf-8", { fatal: true, ignoreBOM: true }).decode(encoded);
  const key = decodePublicKey(text);
  const entry = { keyId: key.fingerprint, algorithm: "minisign-ed25519-blake2b512/1", publicKey: box };
  return `${JSON.stringify({
    schema: "ocx.update.root/1",
    revision: 1,
    expiresAt: "2028-11-07T00:00:00Z",
    rootKeys: [entry],
    rootThreshold: 1,
    releaseKeys: [{ ...entry, channels, roles }],
    releaseThreshold: 1,
    channels,
  }, null, 2)}\n`;
}

function main(): void {
  const expected = generateUpdateTrustRoot(JSON.parse(readFileSync(configPath, "utf8")));
  const fingerprint = createHash("sha256").update(expected, "utf8").digest("hex");
  const outputs = [
    ...rootOutputs.map((path) => ({ path, contents: expected })),
    { path: resolve(repo, "src/update/update-trust-anchor.mjs"), contents: `// Generated by scripts/generate-update-trust-root.ts.\nexport const EMBEDDED_ROOT_SHA256 = "${fingerprint}";\n` },
  ];
  if (process.argv.slice(2).some((arg) => arg !== "--check") || process.argv.slice(2).length > 1) {
    throw new Error("Usage: generate-update-trust-root.ts [--check]");
  }
  if (process.argv[2] === "--check") {
    for (const output of outputs) {
      if (readFileSync(output.path, "utf8") !== output.contents) throw new Error("Generated update trust root is out of date");
    }
    process.stdout.write("Generated update trust roots match the pinned public key\n");
    return;
  }
  for (const output of outputs) {
    const temporary = `${output.path}.${process.pid}.tmp`;
    writeFileSync(temporary, output.contents, { flag: "wx" });
    renameSync(temporary, output.path);
  }
  process.stdout.write("Generated update trust roots\n");
}

if (import.meta.main) main();
