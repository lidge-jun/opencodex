/**
 * Generate the client support matrix pages under docs-site/ from the client registries.
 *
 * bun scripts/generate-client-support-matrix.ts          # write every locale page
 * bun scripts/generate-client-support-matrix.ts --check  # exit 1 when a committed page is stale
 *
 * Rows come from three registries: the export roster (EXPORT_CLIENT_IDS / EXPORT_CLIENTS), the
 * managed file integrations (INTEGRATION_CLIENTS) and the native owners (the
 * NativeIntegrationClientId union, parsed from its declaration). Curated facts live in
 * scripts/client-support-matrix/metadata.ts and are re-checked against the code here, so a stale
 * claim fails generation instead of shipping. Rendering is pure; I/O stays in the CLI entry point.
 */
