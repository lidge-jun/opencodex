const ENDPOINTS: ReadonlyArray<{ protocol: Exclude<MatrixProtocol, "openai-compatible">; route: string }> = [
  { protocol: "responses", route: "/v1/responses" },
  { protocol: "chat-completions", route: "/v1/chat/completions" },
  { protocol: "anthropic-messages", route: "/v1/messages" },
];

// Fixture catalog for protocol checks: one routed model and one native OpenAI model, no secrets,
// loopback listener. Never used to resolve a destination or touch a client's files.
export const FIXTURE_NATIVE_MODEL_ID = "gpt-5.5";
const FIXTURE_MODELS: ExportModel[] = [
  { namespaced: "anthropic/claude-opus-4-8", provider: "anthropic", id: "claude-opus-4-8", contextWindow: 200_000, inputModalities: ["text"] },
  { namespaced: FIXTURE_NATIVE_MODEL_ID, provider: "openai", id: FIXTURE_NATIVE_MODEL_ID, native: true, contextWindow: 400_000, inputModalities: ["text"] },
];
const FIXTURE_CONFIG = { port: 10100, hostname: "127.0.0.1", defaultProvider: "fixture", providers: {} } as unknown as OcxConfig;
const FIXTURE_CONTEXT: ExportContext = { baseUrl: "http://127.0.0.1:10100/v1", models: FIXTURE_MODELS, config: FIXTURE_CONFIG };

export interface ExportSpecFacts {
  format: string;
  loopbackOnly: boolean;
  validateApply?: unknown;
}
export interface IntegrationSpecFacts {
  currentStore?: unknown;
  sourcePreservingYaml?: unknown;
  writerLock?: unknown;
}

/** Everything the generator reads, injectable so tests can mutate one input at a time. */
export interface MatrixInputs {
  exportIds: readonly string[];
  exportSpecs: Readonly<Record<string, ExportSpecFacts>>;
  integrationSpecs: Readonly<Record<string, IntegrationSpecFacts>>;
  inboundRoutes: ReadonlySet<string>;
  buildDocument: (id: string) => unknown;
  readRepoFile: (path: string) => string | undefined;
  exportMetadata: Readonly<Record<string, ExportClientMetadata>>;
  nativeMetadata: Readonly<Record<string, NativeClientMetadata>>;
  /** Text of the runtime results file; undefined when the file is missing. */
  runtimeResultsText: string | undefined;
}

function readRuntimeResultsText(file = join(REPO_ROOT, RUNTIME_RESULTS_FILE)): string | undefined {
  return existsSync(file) ? readFileSync(file, "utf8") : undefined;
}

export function defaultInputs(): MatrixInputs {
  return {
    exportIds: EXPORT_CLIENT_IDS,
    exportSpecs: EXPORT_CLIENTS,
    integrationSpecs: INTEGRATION_CLIENTS,
    inboundRoutes: CONFIGURABLE_JSON_BODY_ROUTES,
    buildDocument: id => buildClientConfigText(id as (typeof EXPORT_CLIENT_IDS)[number], FIXTURE_CONTEXT).document,
    readRepoFile: path => {
      const file = join(REPO_ROOT, path);
      return existsSync(file) ? readFileSync(file, "utf8") : undefined;
    },
    exportMetadata: EXPORT_CLIENT_METADATA,
    nativeMetadata: NATIVE_CLIENT_METADATA,
    runtimeResultsText: readRuntimeResultsText(),
  };
}

type NoteKey = keyof Strings["notes"];
type ProtocolCell = { protocol: MatrixProtocol; nativeOpenaiOnly?: boolean };
export interface MatrixRow {
  id: string;
  label: string;
  native: boolean;
  configExport?: string;
  managed: boolean;
  protocols: ProtocolCell[];
  curated: boolean;
  test?: TestReference;
  notes: NoteKey[];
  guide?: string;
  runtime?: SelectedRuntimeResult;
}

export class MatrixError extends Error {
  constructor(readonly problems: readonly string[]) {
    super(`Client support matrix cannot be generated:\n${problems.map(p => `  - ${p}`).join("\n")}\n` +
      "Fix scripts/client-support-matrix/metadata.ts (or the code it describes), then run: bun run docs:clients");
  }
}

/** Parse `export type NativeIntegrationClientId = "a" | "b";`. Any other shape is refused. */
export function parseNativeRoster(source: string): string[] {
  const match = /^export type NativeIntegrationClientId = ([^;\n]+);$/m.exec(source);
  if (!match) throw new MatrixError([`${NATIVE_ROSTER_FILE} no longer declares NativeIntegrationClientId as a one-line union; update parseNativeRoster`]);
  const members = match[1]!.split("|").map(part => part.trim());
  const ids = members.map(member => /^"([a-z0-9-]+)"$/.exec(member)?.[1]);
  if (ids.some(id => id === undefined)) {
    throw new MatrixError([`NativeIntegrationClientId is not a pure string-literal union: ${match[1]}`]);
  }
  return ids as string[];
}

/**
 * Values at a dotted path; `*` matches every key or array index. `missing` counts the branches
 * that stopped early, so one model without the field cannot hide behind another that has it.
 */
export function valuesAt(document: unknown, path: string): { values: unknown[]; missing: number } {
  let current: unknown[] = [document];
  let missing = 0;
  for (const segment of path.split(".")) {
    const next: unknown[] = [];
    for (const value of current) {
      if (value === null || typeof value !== "object") {
        missing++;
        continue;
      }
      if (segment === "*") next.push(...Object.values(value as Record<string, unknown>));
      else if (Object.prototype.hasOwnProperty.call(value, segment)) next.push((value as Record<string, unknown>)[segment]);
      else missing++;
    }
    current = next;
  }
  return { values: current, missing };
}

function sha256(text: string): string {
  return createHash("sha256").update(text).digest("hex");
}

function exportProtocols(id: string, meta: ExportClientMetadata, inputs: MatrixInputs, problems: string[]): ProtocolCell[] {
  let document: unknown;
  try {
    document = inputs.buildDocument(id);
  } catch (error) {
    problems.push(`${id}: building the fixture export failed: ${(error as Error).message}`);
    return [];
  }
  const seen = new Set<MatrixProtocol>();
  for (const field of meta.protocolFields) {
    const { values, missing } = valuesAt(document, field.path);
    if (values.length === 0 || missing > 0) {
      problems.push(`${id}: protocol field ${field.path} is missing from ${values.length === 0 ? "the generated config" : `${missing} matched entr${missing === 1 ? "y" : "ies"}`}`);
      continue;
    }
    for (const value of values) {
      const text = String(value);
      const key = field.match === "suffix"
        ? Object.keys(field.values).find(suffix => text.endsWith(suffix))
        : Object.prototype.hasOwnProperty.call(field.values, text) ? text : undefined;
      if (key === undefined) problems.push(`${id}: ${field.path} = ${JSON.stringify(text)} is not a protocol value this matrix knows`);
      else seen.add(field.values[key]!);
    }
  }
  const cells: ProtocolCell[] = [...seen].map(protocol => ({ protocol }));
  const override = meta.nativeOpenaiOverride;
  if (override) {
    const entries = valuesAt(document, override.modelsPath).values.flatMap(list => Array.isArray(list) ? list : Object.values(list as object));
    const entryId = (entry: unknown) => (entry as Record<string, unknown>)?.[override.idKey];
    const nativeEntry = entries.find(entry => entryId(entry) === FIXTURE_NATIVE_MODEL_ID);
    if (!nativeEntry) problems.push(`${id}: no model entry for the native OpenAI fixture model at ${override.modelsPath}`);
    else if ((nativeEntry as Record<string, unknown>)[override.field] !== override.value) {
      problems.push(`${id}: the native OpenAI model no longer carries ${override.field} = ${override.value}`);
    }
    for (const entry of entries) {
      if (entryId(entry) === FIXTURE_NATIVE_MODEL_ID) continue;
      if ((entry as Record<string, unknown>)?.[override.field] !== undefined) {
        problems.push(`${id}: model ${String(entryId(entry))} carries ${override.field}; the override is documented for native OpenAI models only`);
      }
    }
    cells.push({ protocol: override.protocol, nativeOpenaiOnly: true });
  }
  if (cells.length === 0 && !problems.some(problem => problem.startsWith(`${id}:`))) {
    problems.push(`${id}: no protocol could be established`);
  }
  return cells;
}

/** Find `test("title"` / `it("title"` exactly once and return its body up to the next case. */
function testCaseBody(source: string, title: string): string | undefined {
  const quoted = JSON.stringify(title);
  const starts = [`test(${quoted}`, `it(${quoted}`].flatMap(opener => {
    const found: number[] = [];
    for (let at = source.indexOf(opener); at >= 0; at = source.indexOf(opener, at + 1)) {
      const before = source[at - 1];
      if (before === undefined || /[\s(;{]/.test(before)) found.push(at);
    }
    return found;
  });
  if (starts.length !== 1) return undefined;
  const afterTitle = source.indexOf(quoted, starts[0]!) + quoted.length;
  const rest = source.slice(afterTitle);
  const next = rest.search(/\n\s*(test|it|describe)(\.\w+)?\(/);
  return withoutComments(next < 0 ? rest : rest.slice(0, next));
}

/** Drop line and block comments so a mention in a comment cannot stand in for code. */
function withoutComments(code: string): string {
  return code.replace(/\/\*[\s\S]*?\*\//g, "").replace(/(^|[^:\\])\/\/.*$/gm, "$1");
}

const DISABLING_MODIFIER = /\b(?:test|it|describe)\.(?:skip|todo|only|skipIf|if|failing|todoIf)\b/;

export function checkTestReference(owner: string, ref: TestReference, readRepoFile: MatrixInputs["readRepoFile"], problems: string[]): void {
  const source = readRepoFile(ref.file);
  if (source === undefined) {
    problems.push(`${owner}: test file ${ref.file} does not exist`);
    return;
  }
  if (DISABLING_MODIFIER.test(source)) {
    problems.push(`${owner}: ${ref.file} uses skip/todo/only/conditional modifiers; link a test from a file without them`);
    return;
  }
  const body = testCaseBody(source, ref.title);
  if (body === undefined) {
    problems.push(`${owner}: ${ref.file} has no single test titled ${JSON.stringify(ref.title)}`);
    return;
  }
  if (!ref.mentions.some(mention => body.includes(mention))) {
    problems.push(`${owner}: test ${JSON.stringify(ref.title)} does not mention ${ref.mentions.join(" or ")}`);
  }
}

export function collectRows(inputs: MatrixInputs = defaultInputs()): MatrixRow[] {
  const problems: string[] = [];
  const exportIds = [...inputs.exportIds];
  const integrationIds = Object.keys(inputs.integrationSpecs);
  for (const id of integrationIds) {
    if (!exportIds.includes(id)) problems.push(`${id}: managed file integration without an export registry entry; the matrix has no row shape for it`);
  }
  for (const id of Object.keys(inputs.exportMetadata)) {
    if (!exportIds.includes(id)) problems.push(`${id}: metadata exists for a client that is no longer in EXPORT_CLIENT_IDS; remove it`);
  }

  const nativeSource = inputs.readRepoFile(NATIVE_ROSTER_FILE);
  let nativeIds: string[] = [];
  if (nativeSource === undefined) problems.push(`${NATIVE_ROSTER_FILE} is missing`);
  else {
    try {
      nativeIds = parseNativeRoster(nativeSource);
    } catch (error) {
      problems.push(...(error as MatrixError).problems);
    }
  }
  for (const id of nativeIds) if (!inputs.nativeMetadata[id]) problems.push(`${id}: native integration owner without metadata; add it to NATIVE_CLIENT_METADATA`);
  for (const id of Object.keys(inputs.nativeMetadata)) {
    if (nativeSource !== undefined && !nativeIds.includes(id)) problems.push(`${id}: native metadata for an owner that is no longer in NativeIntegrationClientId; remove it`);
  }

  for (const { route } of ENDPOINTS) {
    if (!inputs.inboundRoutes.has(route)) problems.push(`inbound route ${route} is no longer admitted; update ENDPOINTS`);
  }

  const rows: MatrixRow[] = [];
  // Metadata order is the display order; the parsed union decides membership.
  for (const id of Object.keys(inputs.nativeMetadata).filter(id => nativeIds.includes(id))) {
    const meta = inputs.nativeMetadata[id]!;
    for (const anchor of meta.anchors) {
      const source = inputs.readRepoFile(anchor.file);
      if (source === undefined || !withoutComments(source).includes(anchor.text)) {
        problems.push(`${id}: reviewed code ${JSON.stringify(anchor.text)} is no longer in ${anchor.file}; re-review the curated protocol`);
      }
    }
    if (meta.test) checkTestReference(id, meta.test, inputs.readRepoFile, problems);
    rows.push({ id, label: meta.label, native: true, managed: false, protocols: meta.protocols.map(protocol => ({ protocol })), curated: true, test: meta.test, notes: ["native"], guide: meta.guide });
  }

  for (const id of exportIds) {
    const meta = inputs.exportMetadata[id];
    const spec = inputs.exportSpecs[id];
    if (!meta) {
      problems.push(`${id}: export client without metadata; add it to EXPORT_CLIENT_METADATA`);
      continue;
    }
    if (!spec) {
      problems.push(`${id}: listed in EXPORT_CLIENT_IDS but missing from EXPORT_CLIENTS`);
      continue;
    }
    const protocols = exportProtocols(id, meta, inputs, problems);
    if (meta.clientSelected) {
      const source = inputs.readRepoFile(meta.clientSelected.file);
      if (source === undefined || !source.includes(meta.clientSelected.anchor)) {
        problems.push(`${id}: the reviewed sentence is no longer in ${meta.clientSelected.file}; re-review the client-selected protocol`);
      } else if (sha256(source) !== meta.clientSelected.reviewedSha) {
        problems.push(`${id}: ${meta.clientSelected.file} changed since its protocol was reviewed (sha256 ${sha256(source)}); re-review the client-selected protocol, then update reviewedSha`);
      }
    }
    if (meta.test) checkTestReference(id, meta.test, inputs.readRepoFile, problems);
    const integration = inputs.integrationSpecs[id];
    const notes: NoteKey[] = [spec.loopbackOnly ? "loopbackOnly" : "remoteWithKey"];
    if (integration?.currentStore) notes.push("currentStore");
    if (integration?.sourcePreservingYaml) notes.push("sourcePreservingYaml");
    if (integration?.writerLock) notes.push("writerLock");
    if (spec.validateApply) notes.push("validateApply");
    if (meta.clientSelected) notes.push("clientSelected");
    rows.push({ id, label: meta.label, native: false, configExport: spec.format.toUpperCase(), managed: integration !== undefined, protocols, curated: meta.clientSelected !== undefined, test: meta.test, notes, guide: meta.guide });
  }

  const runtime = parseRuntimeResults(inputs.runtimeResultsText, new Set(rows.map(row => row.id)), RUNTIME_RESULTS_FILE);
  problems.push(...runtime.problems);
  const selected = selectRuntimeResults(runtime.results);
  for (const row of rows) {
    const result = selected.get(row.id);
    if (result) row.runtime = result;
  }

  if (problems.length > 0) throw new MatrixError(problems);
  return rows;
}

function cell(text: string): string {
  return text.replace(/\|/g, "\\|").replace(/\n/g, " ");
}

function localePrefix(locale: MatrixLocale): string {
  return locale === "root" ? "/" : `/${locale}/`;
}

function protocolText(entry: ProtocolCell, strings: Strings): string {
  const name = entry.protocol === "openai-compatible" ? strings.openaiCompatible : PROTOCOL_NAMES[entry.protocol];
  return entry.nativeOpenaiOnly ? `${name} (${strings.nativeOpenaiCondition})` : name;
}

/** Validated fields carry no Markdown-breaking characters, so they are rendered as written. */
function runtimeCell(entry: SelectedRuntimeResult | undefined, s: Strings): string {
  if (!entry) return "—";
  const r = entry.result;
  const more = entry.others > 0 ? ` ${s.runtimeMore.replace("{n}", String(entry.others))}` : "";
  return `${r.product} ${r.clientVersion} + opencodex ${r.opencodexVersion}: ${r.scenario} (${r.verifiedOn}, [${s.evidenceLink}](${r.evidence}))${more}`;
}

export function renderPage(rows: readonly MatrixRow[], locale: MatrixLocale): string {
  const s: Strings = LOCALES[locale];
  const c = s.columns;
  const lines = [
    "---",
    `title: ${JSON.stringify(s.title)}`,
    `description: ${JSON.stringify(s.description)}`,
    "---",
    "",
    `<!-- ${OWNER}. Do not edit by hand. -->`,
    "<!-- Regenerate: bun run docs:clients -->",
    "",
    s.intro,
    "",
    `## ${s.levelsHeading}`,
    "",
    `- **implemented**: ${s.implementedDefinition}`,
    `- **test-covered**: ${s.testCoveredDefinition}`,
    `- **${s.columns.runtime}**: ${s.runtimeDefinition}`,
    "",
    `## ${s.clientsHeading}`,
    "",
    `| ${c.client} | ${c.native} | ${c.configExport} | ${c.managed} | ${c.protocol} | ${c.level} | ${c.runtime} | ${c.notes} |`,
    "| --- | --- | --- | --- | --- | --- | --- | --- |",
  ];
  for (const row of rows) {
    const protocol = row.protocols.map(entry => protocolText(entry, s)).join("; ") + (row.curated ? ` (${s.curated})` : "");
    const level = row.test ? `test-covered ([${s.testLink}](${REPO_BLOB}${row.test.file}))` : "implemented";
    const separator = locale === "zh-cn" || locale === "zh-tw" || locale === "ja" ? "" : " ";
    const notes = row.notes.map(key => s.notes[key]).join(separator) + (row.guide ? ` [${s.guideLink}](${localePrefix(locale)}${row.guide}/)` : "");
    lines.push(`| ${cell(row.label)} | ${row.native ? s.yes : "—"} | ${row.configExport ?? "—"} | ${row.managed ? s.yes : "—"} | ${cell(protocol)} | ${level} | ${runtimeCell(row.runtime, s)} | ${cell(notes)} |`);
  }
  lines.push("", `## ${s.endpointsHeading}`, "", s.endpointsIntro, "");
  for (const { protocol, route } of ENDPOINTS) lines.push(`- \`POST ${route}\`: ${PROTOCOL_NAMES[protocol]}`);
  lines.push("", `## ${s.maintenanceHeading}`, "", s.maintenance, "");
  return lines.join("\n");
}

export function pagePath(locale: MatrixLocale): string {
  return join("docs-site", "src", "content", "docs", ...(locale === "root" ? [] : [locale]), PAGE).split("\\").join("/");
}

/** Expected bytes for every owned page, keyed by repository-relative path. */
export function renderAll(inputs: MatrixInputs = defaultInputs()): Record<string, string> {
  const rows = collectRows(inputs);
  const pages: Record<string, string> = {};
  for (const locale of Object.keys(LOCALES) as MatrixLocale[]) pages[pagePath(locale)] = renderPage(rows, locale);
  return pages;
}

if (import.meta.main) {
  const check = process.argv.includes("--check");
  const dataFlag = process.argv.indexOf("--runtime-data");
  if (dataFlag >= 0 && (!check || !process.argv[dataFlag + 1])) {
    console.error("--runtime-data <path> is only accepted together with --check; pages are always generated from the committed file.");
    process.exit(1);
  }
  let pages: Record<string, string>;
  try {
    if (dataFlag >= 0) {
      // Validate the extra file against the same rows; the committed file is still checked below.
      collectRows({ ...defaultInputs(), runtimeResultsText: readRuntimeResultsText(process.argv[dataFlag + 1]!) });
    }
    pages = renderAll();
  } catch (error) {
    console.error(error instanceof MatrixError ? error.message : error);
    process.exit(1);
  }
  const stale: string[] = [];
  for (const [path, text] of Object.entries(pages)) {
    const file = join(REPO_ROOT, path);
    const current = existsSync(file) ? readFileSync(file, "utf8") : undefined;
    if (current === text) continue;
    if (check) stale.push(path);
    else writeFileSync(file, text);
  }
  if (check && stale.length > 0) {
    console.error(`Client support pages are stale: ${stale.join(", ")}\nRun: bun run docs:clients`);
    process.exit(1);
  }
  console.log(check ? "Client support pages are current." : `Wrote ${Object.keys(pages).length} client support pages.`);
}
