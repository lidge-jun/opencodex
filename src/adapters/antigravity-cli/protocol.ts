function structuredOutputInstructions(format: OcxRequestOptions["textFormat"]): string {
  if (!format) return "";
  const schema = format.type === "json_schema" && format.schema
    ? `\nYour final JSON must conform to this JSON Schema:\n${JSON.stringify(format.schema)}`
    : "";
  const kind = format.type === "json_object" ? "JSON object" : "JSON value";
  return `[Final response format]\nWhen ready to answer, return only a valid ${kind}: no Markdown, no code fences, no headings or prose outside the JSON. `
    + "Do not emit any prose or narration before or between tool calls (including view_file); output text only once when returning the final JSON."
    + schema;
}

function isPlainSchemaRecord(value: unknown): value is Record<string, unknown> {
  if (value === null || typeof value !== "object" || Array.isArray(value)) return false;
  const proto = Object.getPrototypeOf(value);
  return proto === Object.prototype || proto === null;
}

function hasExternalSchemaRef(value: unknown, active = new WeakSet<object>(), depth = 0): boolean {
  if (depth > 64 || value === null || typeof value !== "object") return false;
  if (active.has(value)) return true;
  active.add(value);
  try {
    if (Array.isArray(value)) {
      return value.some(item => hasExternalSchemaRef(item, active, depth + 1));
    }
    if (!isPlainSchemaRecord(value)) return false;
    for (const [key, entry] of Object.entries(value)) {
      if ((key === "$ref" || key === "$dynamicRef") && typeof entry === "string" && !entry.startsWith("#")) {
        return true;
      }
      if (hasExternalSchemaRef(entry, active, depth + 1)) return true;
    }
    return false;
  } finally {
    active.delete(value);
  }
}

/** Build the validated per-turn isolated MCP tool catalog mapped to `agy` eager tool names. */
export function buildAntigravityCliToolBridge(parsed: OcxParsedRequest): AntigravityCliToolBridge | undefined {
  const rawTools = parsed.context.tools;
  const preSanitizedTools = rawTools && rawTools.length > 0
    ? rawTools.map(tool => {
        if (!isPlainSchemaRecord(tool.parameters) || hasExternalSchemaRef(tool.parameters)) {
          return tool;
        }
        return {
          ...tool,
          parameters: sanitizeGeminiToolParametersWithReport(tool.parameters, {
            endpointClass: "cloud-code-assist",
          }).parameters,
        };
      })
    : rawTools;
  const bridgeInput: OcxParsedRequest = preSanitizedTools === rawTools
    ? parsed
    : { ...parsed, context: { ...parsed.context, tools: preSanitizedTools } };
  const bridge = stableClaudeToolBridge(buildCodeBuddyToolBridge(bridgeInput, ANTIGRAVITY_TOOL_LIMITS));
  if (bridge.tools.length === 0) return undefined;
  const emittedNameMap = new Map<string, string>();
  for (const [codeBuddyName, wireName] of bridge.emittedNameMap) {
    const alias = codeBuddyName.startsWith(CODEBUDDY_MCP_TOOL_PREFIX)
      ? codeBuddyName.slice(CODEBUDDY_MCP_TOOL_PREFIX.length)
      : codeBuddyName;
    emittedNameMap.set(`${ANTIGRAVITY_MCP_TOOL_PREFIX}${alias}`, wireName);
  }
  const tools = bridge.tools.map(tool => {
    const sanitizedDesc = sanitizeAntigravityProxyArtifacts(tool.description);
    // Cloud Code Assist rejects JSON Schema keywords outside Gemini's protobuf FunctionDeclaration
    // subset (for example bare `type: "array"` without `items`, `prefixItems`, `$ref`, `additionalProperties`)
    // with HTTP 400 `INVALID_ARGUMENT` (#5689). Canonicalize after sanitizing so null-prototype maps
    // become deterministic plain objects.
    const sanitizedSchema = canonicalClaudeJson(
      sanitizeGeminiToolParametersWithReport(tool.inputSchema, { endpointClass: "cloud-code-assist" }).parameters,
    ) as Record<string, unknown>;
    return {
      ...tool,
      description: sanitizedDesc,
      inputSchema: sanitizedSchema,
    };
  });
  return {
    serverName: ANTIGRAVITY_MCP_SERVER_NAME,
    tools,
    emittedNameMap,
    maxTurnToolCalls: ANTIGRAVITY_TOOL_LIMITS.maxTurnToolCalls,
    requireToolCall: bridge.requireToolCall,
  };
}

/**
 * Split leading `developer` instructions (which belong in `agent.md` system rules) from
 * chronological conversation messages (including mid-conversation `developer` reminders injected
 * per turn by Claude Code / Desktop `role: "system"` entries, so `agent.md` stays byte-stable).
 */
export function partitionAntigravityMessages(messages: readonly OcxMessage[]): {
  leadingDeveloper: OcxMessage[];
  conversation: OcxMessage[];
} {
  const leadingDeveloper: OcxMessage[] = [];
  const conversation: OcxMessage[] = [];
  let seenNonDeveloper = false;
  for (const message of messages) {
    if (!seenNonDeveloper && message.role === "developer") {
      leadingDeveloper.push(message);
    } else {
      seenNonDeveloper = true;
      conversation.push(message);
    }
  }
  return { leadingDeveloper, conversation };
}

/** Fold caller system and leading developer instructions with replay, staged-image, structured-output, and tool-bridge contracts. */
export function buildAntigravityCliRulesMarkdown(
  parsed: OcxParsedRequest,
  toolBridge?: AntigravityCliToolBridge,
  hasStagedImages = false,
): string {
  const systemParts: string[] = [];
  for (const rawLine of parsed.context.systemPrompt ?? []) {
    if (!rawLine) continue;
    const cleaned = sanitizeAntigravitySystemText(rawLine, parsed.modelId).trim();
    if (cleaned) systemParts.push(cleaned);
  }
  const { leadingDeveloper } = partitionAntigravityMessages(parsed.context.messages);
  for (const message of leadingDeveloper) {
    const rawText = typeof message.content === "string"
      ? message.content
      : message.content.map(part => (part.type === "text" || part.type === "document" ? part.text : "")).join("");
    const cleaned = sanitizeAntigravitySystemText(rawText, parsed.modelId).trim();
    if (cleaned) systemParts.push(cleaned);
  }
  const callerSystem = systemParts.join("\n\n");
  const imageSection = hasStagedImages ? ANTIGRAVITY_STAGED_IMAGE_SYSTEM_PROMPT : "";
  const formatSection = structuredOutputInstructions(parsed.options.textFormat);
  const disabledPrompt = hasStagedImages
    ? [
        "The local CLI working directory is an empty isolated sandbox container; all real project and file paths come from the client conversation.",
        "User MCP servers and all built-in Antigravity CLI tools except read-only `view_file` on `.ocx-images/*` are disabled for this proxied turn.",
        "After inspecting any attached `.ocx-images/*` files, answer directly without claiming workspace side effects.",
        ANTIGRAVITY_ISOLATION_AND_REPLAY_RULES,
      ].join("\n")
    : `${ANTIGRAVITY_TOOL_DISABLED_SYSTEM_PROMPT}\n${ANTIGRAVITY_ISOLATION_AND_REPLAY_RULES}`;
  const toolSection = toolBridge
    ? [
        ANTIGRAVITY_TOOL_BRIDGE_SYSTEM_PROMPT,
        "External tool names in client instructions correspond to these exact callable MCP tool names:\n"
          + JSON.stringify(Object.fromEntries([...toolBridge.emittedNameMap].map(([cliName, wireName]) => [wireName, cliName]))),
      ].join("\n\n")
    : disabledPrompt;

  return [callerSystem, CLAUDE_REPLAY_SYSTEM_PROMPT, imageSection, formatSection, toolSection].filter(Boolean).join("\n\n");
}

/**
 * Build `.agents/agents/ocx_bridge/agent.md` for `--agent ocx_bridge`.
 *
 * Unlike `.agents/rules/AGENTS.md` (which appends to `agy`'s built-in IDE system prompt and leaves
 * global user MCP servers and 50+ built-in tools visible), a custom main agent replaces `agy`'s
 * system prompt with its Markdown body, sets `inheritMcp: false` to exclude all user global MCP
 * servers, restricts `tools` to `[]` (or `["view_file"]` when base64 images are staged), and keeps
 * `inheritCustomizations: true` so `.agents/hooks.json` (`ocx-pretool-guard`) executes.
 */
export function buildAntigravityAgentMarkdown(
  parsed: OcxParsedRequest,
  options: {
    toolBridge?: AntigravityCliToolBridge;
    hasStagedImages?: boolean;
    mcpServer?: { command: string; args: readonly string[] };
  } = {},
): string {
  const hasStagedImages = options.hasStagedImages === true;
  const frontmatter: string[] = [
    "---",
    `name: ${ANTIGRAVITY_BRIDGE_AGENT_NAME}`,
    "description: Isolated stateless turn bridge",
    "mainAgent: true",
    "subagent: false",
    "model: inherit",
    "inheritCustomizations: true",
    "inheritMcp: false",
    `tools: ${hasStagedImages ? '["view_file"]' : "[]"}`,
  ];
  if (options.toolBridge && options.mcpServer) {
    frontmatter.push(
      "mcpServers:",
      `  - name: ${JSON.stringify(options.toolBridge.serverName)}`,
      `    command: ${JSON.stringify(options.mcpServer.command)}`,
      `    args: ${JSON.stringify([...options.mcpServer.args])}`,
      "    tools:",
    );
    for (const tool of options.toolBridge.tools) {
      frontmatter.push(`      ${JSON.stringify(tool.name)}:`, "        eager: true");
    }
  }
  frontmatter.push("---");
  const body = buildAntigravityCliRulesMarkdown(parsed, options.toolBridge, hasStagedImages);
  return `${frontmatter.join("\n")}\n\n${body}\n`;
}

const DATA_IMAGE_URL_RE = /^data:image\/(png|jpeg|jpg|gif|webp|bmp|tiff);base64,([A-Za-z0-9+/=\s]+)$/i;
