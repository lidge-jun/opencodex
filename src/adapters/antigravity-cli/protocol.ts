export function capUtf8Bytes(text: string, maxBytes: number, fromTail = false): string {
  if (maxBytes <= 0 || !text) return "";
  const buf = Buffer.from(text, "utf8");
  if (buf.byteLength <= maxBytes) return text;
  if (fromTail) {
    let start = buf.byteLength - maxBytes;
    while (start < buf.byteLength && (buf[start]! & 0xc0) === 0x80) start += 1;
    return buf.subarray(start).toString("utf8");
  }
  let end = maxBytes;
  if (end < buf.byteLength && (buf[end]! & 0xc0) === 0x80) {
    while (end > 0 && (buf[end]! & 0xc0) === 0x80) end -= 1;
  }
  return buf.subarray(0, end).toString("utf8");
}

