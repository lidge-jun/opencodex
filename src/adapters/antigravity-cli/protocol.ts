function normalizeImageExtension(subtype: string): string {
  const lower = subtype.toLowerCase();
  return lower === "jpeg" ? "jpg" : lower;
}

function decodedBase64ByteLength(cleanBase64: string): number {
  const padding = cleanBase64.endsWith("==") ? 2 : cleanBase64.endsWith("=") ? 1 : 0;
  return (cleanBase64.length / 4) * 3 - padding;
}

function relativePathForImagePart(imageUrl: string, ordinal: number): string {
  const match = /^data:image\/(png|jpeg|jpg|gif|webp|bmp|tiff);base64,/i.exec(imageUrl.trim());
  const ext = match ? normalizeImageExtension(match[1]!) : "png";
  return `.ocx-images/img-${ordinal}.${ext}`;
}

export function stableAntigravityMessageText(
  message: OcxMessage,
  vendorNameByWire?: ReadonlyMap<string, string>,
  modelId?: string,
): string {
  if (message.role === "developer") {
    const rawText = typeof message.content === "string"
      ? message.content
      : message.content.map(part => (part.type === "text" || part.type === "document" ? part.text : "")).join("");
    const cleaned = sanitizeAntigravitySystemText(rawText, modelId).trim();
    return cleaned ? `[System reminder]\n${cleaned}` : "";
  }
  if (message.role !== "assistant") {
    return formatMessageForHistory(message, vendorNameByWire, false, { omitThinking: true });
  }
  const rewritten: OcxMessage = {
    ...message,
    content: message.content.map(part => part.type === "toolCall"
      ? { ...part, arguments: canonicalClaudeJson(part.arguments ?? {}) as Record<string, unknown> }
      : part),
  };
  return formatMessageForHistory(rewritten, vendorNameByWire, false, { omitThinking: true });
}

const stableMessageText = stableAntigravityMessageText;

function formatMessageWithImageMarkers(
  message: OcxMessage,
  vendorNameByWire: ReadonlyMap<string, string> | undefined,
  renderImageMarker: (imageUrl: string) => string,
  modelId?: string,
): string {
  if (
    (message.role !== "user" && message.role !== "toolResult")
    || typeof message.content === "string"
    || !message.content.some(part => part.type === "image")
  ) {
    return stableMessageText(message, vendorNameByWire, modelId);
  }
  const rendered = message.content.map(part => {
    if (part.type === "text" || part.type === "document") return part.text;
    if (part.type === "image") return renderImageMarker(part.imageUrl);
    return `[${part.type}]`;
  }).join("\n");
  if (message.role === "user") return `USER:\n${rendered}`;
  const status = message.isError ? " (error)" : "";
  return `TOOL RESULT (call_id: ${message.toolCallId})${status}:\n${rendered}`;
}

function computeOmittedMessageCount(
  messages: readonly OcxMessage[],
  blockSizes: readonly number[],
  maxHistoryChars?: number,
): number {
  const requestedLimit = maxHistoryChars ?? ANTIGRAVITY_COLD_HISTORY_CHAR_LIMIT;
  const limit = Number.isFinite(requestedLimit) && requestedLimit >= 0
    ? Math.floor(requestedLimit)
    : ANTIGRAVITY_COLD_HISTORY_CHAR_LIMIT;
  const historySizes = blockSizes.slice(0, -1);
  let omitted = 0;
  if (historySizes.length > 0) {
    const tailSize = blockSizes.at(-1) ?? 0;
    const historyWithSeps = historySizes.reduce((sum, size) => sum + size + 2, 0);
    if (historyWithSeps + tailSize > limit) {
      const availableForHistory = Math.max(0, limit - tailSize - TRUNCATION_NOTICE.length - 2);
      const step = Math.max(1, Math.min(20_000, Math.floor(limit / 10)));
      const dropTarget = Math.ceil(Math.max(1, historyWithSeps - availableForHistory) / step) * step;
      let removedChars = 0;
      while (omitted < historySizes.length && removedChars < dropTarget) {
        removedChars += historySizes[omitted++]! + 2;
      }
      while (omitted < historySizes.length && messages[omitted]!.role === "toolResult") omitted++;
      const current = messages.at(-1);
      if (current?.role === "toolResult") {
        const callIndex = messages.slice(0, -1).findLastIndex(message => message.role === "assistant"
          && message.content.some(part => part.type === "toolCall" && part.id === current.toolCallId));
        if (callIndex >= 0 && omitted > callIndex) {
          const remainingFromCall = (callIndex > 0 ? TRUNCATION_NOTICE.length + 2 : 0)
            + historySizes.slice(callIndex).reduce((sum, size) => sum + size + 2, 0)
            + tailSize;
          if (remainingFromCall <= limit) omitted = callIndex;
        }
      }
    }
  }
  return omitted;
}

/**
 * Validate media parts and extract inline base64 raster images for read-only `.ocx-images/` staging.
 *
 * `agy --input-format stream-json` rejects inline image content blocks on stdin, so `user` and
 * `toolResult` `data:image/(png|jpeg|jpg|gif|webp|bmp|tiff);base64,...` attachments are decoded
 * into `turnDir/.ocx-images/` (`0600`) and read via `view_file`. Developer/system instruction
 * images, file-backed image IDs, remote `http(s)://` image URLs, SVG, video, or active-turn
 * attachments exceeding `16` images / `32 MiB` fail closed with HTTP 400 before spawning `agy`,
 * while truncated (`index < omitted`) or aged-out historical screenshots beyond the 16-image /
 * 32 MiB window are omitted cleanly so long screenshot-heavy sessions keep working.
 */
export function extractAntigravityStagedImages(
  parsed: OcxParsedRequest,
  options: {
    maxHistoryChars?: number;
    vendorNameByWire?: ReadonlyMap<string, string>;
    validateOnly?: boolean;
  } = {},
): { images: AntigravityStagedImageSpec[]; error?: undefined } | { images?: undefined; error: string } {
  const rawBody = asRecord(parsed._rawBody);
  if (responsesHasInstructionImage(parsed._rawBody) || (rawBody && chatHasInstructionImage(rawBody))) {
    return { error: "Antigravity CLI does not support images in developer or system instructions." };
  }
  if (responsesHasFileImage(parsed._rawBody)) {
    return { error: "Antigravity CLI does not support file-backed image references." };
  }

  interface CandidateImage {
    ordinal: number;
    msgIndex: number;
    fileName: string;
    relativePath: string;
    cleanBase64: string;
    byteLength: number;
  }
  const candidates: CandidateImage[] = [];
  const conversationMessages: OcxMessage[] = [];
  let seenNonDeveloper = false;

  for (const message of parsed.context.messages) {
    const isDeveloper = message.role === "developer";
    if (!isDeveloper) seenNonDeveloper = true;
    const inConversation = seenNonDeveloper;
    const msgIndex = inConversation ? conversationMessages.length : -1;
    if (inConversation) conversationMessages.push(message);

    if (!Array.isArray(message.content)) continue;
    for (const part of message.content) {
      if (part.type === "video") {
        return { error: `Antigravity CLI does not support video input (video part in ${message.role} message).` };
      }
      if (part.type !== "image") continue;
      if (isDeveloper) {
        return { error: "Antigravity CLI does not support images in developer or system instructions." };
      }
      if (message.role !== "user" && message.role !== "toolResult") {
        return { error: `Antigravity CLI does not support image attachments in ${message.role} messages.` };
      }
      const match = DATA_IMAGE_URL_RE.exec(part.imageUrl.trim());
      if (!match) {
        return {
          error:
            "Antigravity CLI supports inline base64 raster images (png, jpeg, gif, webp, bmp, tiff) only; remote image URLs and unsupported formats are rejected.",
        };
      }
      const cleanBase64 = match[2]!.replace(/\s+/g, "");
      if (!cleanBase64 || cleanBase64.length % 4 !== 0 || !STRICT_BASE64_RE.test(cleanBase64)) {
        return { error: "Antigravity CLI received a malformed base64 image payload." };
      }
      const byteLength = decodedBase64ByteLength(cleanBase64);
      if (byteLength <= 0) {
        return { error: "Antigravity CLI received an empty base64 image payload." };
      }
      const ordinal = candidates.length;
      const ext = normalizeImageExtension(match[1]!);
      const fileName = `img-${ordinal}.${ext}`;
      candidates.push({
        ordinal,
        msgIndex,
        fileName,
        relativePath: `.ocx-images/${fileName}`,
        cleanBase64,
        byteLength,
      });
    }
  }

  if (candidates.length === 0) return { images: [] };

  const lastAssistantIndex = conversationMessages.findLastIndex(message => message.role === "assistant");
  let activeCount = 0;
  let activeBytes = 0;
  for (const candidate of candidates) {
    if (candidate.msgIndex > lastAssistantIndex) {
      activeCount += 1;
      activeBytes += candidate.byteLength;
    }
  }
  if (activeCount > MAX_ANTIGRAVITY_STAGED_IMAGES) {
    return { error: `Antigravity CLI supports at most ${MAX_ANTIGRAVITY_STAGED_IMAGES} attached images per turn.` };
  }
  if (activeBytes > MAX_ANTIGRAVITY_STAGED_IMAGE_BYTES) {
    return { error: "Antigravity CLI attached image payloads exceeded the 32 MiB per-turn limit." };
  }
  if (options.validateOnly) return { images: [] };

  let canonicalOrdinal = 0;
  const canonicalSizes = conversationMessages.map(message =>
    formatMessageWithImageMarkers(
      message,
      options.vendorNameByWire,
      imageUrl => `[Attached image: ${relativePathForImagePart(imageUrl, canonicalOrdinal++)}]`,
      parsed.modelId,
    ).length,
  );
  const omitted = computeOmittedMessageCount(conversationMessages, canonicalSizes, options.maxHistoryChars);

  const selectedReversed: CandidateImage[] = [];
  let selectedBytes = 0;
  for (let i = candidates.length - 1; i >= 0; i--) {
    const candidate = candidates[i]!;
    if (candidate.msgIndex < omitted) continue;
    if (
      selectedReversed.length < MAX_ANTIGRAVITY_STAGED_IMAGES
      && selectedBytes + candidate.byteLength <= MAX_ANTIGRAVITY_STAGED_IMAGE_BYTES
    ) {
      selectedReversed.push(candidate);
      selectedBytes += candidate.byteLength;
    }
  }
  selectedReversed.reverse();

  return {
    images: selectedReversed.map(candidate => ({
      index: candidate.ordinal,
      fileName: candidate.fileName,
      relativePath: candidate.relativePath,
      bytes: Buffer.from(candidate.cleanBase64, "base64"),
    })),
  };
}

export function findUnsupportedAntigravityInputModality(parsed: OcxParsedRequest): string | undefined {
  return extractAntigravityStagedImages(parsed, { validateOnly: true }).error;
}

/**
 * Project OpenCodex conversation history into the single `{ event: "user", message: { content } }`
 * JSONL frame `agy --input-format stream-json` consumes on stdin.
 *
 * Historical message blocks render deterministic `.ocx-images/img-<n>.<ext>` markers so prefix
 * prompt caching stays byte-identical across turns, while the current turn's resolved workspace
 * absolute paths are appended in a single trailing block at the uncached tail.
 */
export function buildAntigravityCliConversationInput(
  parsed: OcxParsedRequest,
  options: {
    historyCharLimit?: number;
    maxHistoryChars?: number;
    vendorNameByWire?: ReadonlyMap<string, string>;
    stagedImages?: ReadonlyArray<{ index: number; relativePath: string; absolutePath: string }>;
    stagedImagePaths?: readonly string[];
  } = {},
): string[] {
  const { conversation: messages } = partitionAntigravityMessages(parsed.context.messages);
  let canonicalOrdinal = 0;
  const canonicalBlocks = messages.map(message =>
    formatMessageWithImageMarkers(
      message,
      options.vendorNameByWire,
      imageUrl => `[Attached image: ${relativePathForImagePart(imageUrl, canonicalOrdinal++)}]`,
      parsed.modelId,
    ),
  );
  if (canonicalBlocks.length === 0) canonicalBlocks.push("");
  const omitted = computeOmittedMessageCount(
    messages,
    canonicalBlocks.map(block => block.length),
    options.historyCharLimit ?? options.maxHistoryChars,
  );

  let renderedBlocks = canonicalBlocks;
  const footerEntries: Array<{ relativePath: string; absolutePath: string }> = [];

  if (options.stagedImages !== undefined) {
    const stagedByIndex = new Map(options.stagedImages.map(item => [item.index, item]));
    let ordinal = 0;
    renderedBlocks = messages.map(message =>
      formatMessageWithImageMarkers(message, options.vendorNameByWire, () => {
        const current = stagedByIndex.get(ordinal++);
        return current ? `[Attached image: ${current.relativePath}]` : "[Historical image omitted]";
      }, parsed.modelId),
    );
    if (renderedBlocks.length === 0) renderedBlocks.push("");
    for (const item of options.stagedImages) {
      footerEntries.push({ relativePath: item.relativePath, absolutePath: item.absolutePath });
    }
  } else if (options.stagedImagePaths !== undefined) {
    let ordinal = 0;
    renderedBlocks = messages.map((message, msgIndex) =>
      formatMessageWithImageMarkers(message, options.vendorNameByWire, imageUrl => {
        const idx = ordinal++;
        const absPath = options.stagedImagePaths?.[idx];
        if (!absPath) return "[Historical image omitted]";
        const relativePath = relativePathForImagePart(imageUrl, idx);
        if (msgIndex >= omitted) footerEntries.push({ relativePath, absolutePath: absPath });
        return `[Attached image: ${relativePath}]`;
      }, parsed.modelId),
    );
    if (renderedBlocks.length === 0) renderedBlocks.push("");
  }

  const content: Array<{ type: "text"; text: string }> = [];
  const pushBlock = (block: string): void => {
    content.push({ type: "text", text: content.length === 0 ? block : `\n\n${block}` });
  };
  if (omitted > 0) pushBlock(TRUNCATION_NOTICE);
  for (let index = omitted; index < renderedBlocks.length; index++) {
    pushBlock(renderedBlocks[index]!);
  }
  if (footerEntries.length > 0) {
    pushBlock([
      "[Workspace absolute paths for attached images — pass exact path to view_file:",
      ...footerEntries.map(entry => `- ${entry.relativePath} -> ${entry.absolutePath}`),
      "]",
    ].join("\n"));
  }
  return [JSON.stringify({ event: "user", message: { content } })];
}

export function usageFromAntigravityRecord(usage: Record<string, unknown> | undefined): OcxUsage | undefined {
  if (!usage) return undefined;
  const count = (value: unknown): number =>
    typeof value === "number" && Number.isFinite(value) && value >= 0 ? Math.floor(value) : 0;
  const rawInput = count(usage.input_tokens);
  const rawOutput = count(usage.output_tokens);
  const cacheRead = count(usage.cache_read_tokens);
  const thinking = count(usage.thinking_tokens);
  const rawTotal = count(usage.total_tokens);
  const baseInput = rawInput + cacheRead;
  const inputInTotal = rawTotal >= baseInput + rawOutput ? baseInput : rawInput;
  const outputTokens = thinking > 0 && rawOutput > 0 && rawTotal >= inputInTotal + rawOutput + thinking
    ? rawOutput + thinking
    : Math.max(rawOutput, thinking);
  const inputTokens = rawInput === 0 && cacheRead > 0 && rawTotal > cacheRead + outputTokens
    ? rawTotal - outputTokens
    : baseInput;
  if (inputTokens === 0 && outputTokens === 0 && cacheRead === 0 && thinking === 0 && rawTotal === 0) {
    return undefined;
  }
  return {
    inputTokens,
    outputTokens,
    totalTokens: Math.max(rawTotal, inputTokens + outputTokens),
    ...(cacheRead > 0 ? { cachedInputTokens: cacheRead, cacheReadInputTokens: cacheRead } : {}),
    ...(thinking > 0 ? { reasoningOutputTokens: thinking } : {}),
  };
}

function mergeAntigravityUsage(previous: OcxUsage | undefined, next: OcxUsage): OcxUsage {
  if (!previous) return next;
  const cacheRead = Math.max(
    previous.cacheReadInputTokens ?? previous.cachedInputTokens ?? 0,
    next.cacheReadInputTokens ?? next.cachedInputTokens ?? 0,
  );
  const reasoning = Math.max(previous.reasoningOutputTokens ?? 0, next.reasoningOutputTokens ?? 0);
  const freshInput = (u: OcxUsage): number =>
    Math.max(0, u.inputTokens - (u.cacheReadInputTokens ?? u.cachedInputTokens ?? 0));
  const inputTokens = Math.max(freshInput(previous), freshInput(next)) + cacheRead;
  const outputTokens = Math.max(previous.outputTokens, next.outputTokens, reasoning);
  const totalTokens = Math.max(previous.totalTokens ?? 0, next.totalTokens ?? 0, inputTokens + outputTokens);
  return {
    inputTokens,
    outputTokens,
    totalTokens,
    ...(cacheRead > 0 ? { cachedInputTokens: cacheRead, cacheReadInputTokens: cacheRead } : {}),
    ...(reasoning > 0 ? { reasoningOutputTokens: reasoning } : {}),
  };
}

export interface RawAntigravityUsage {
  input_tokens: number;
  output_tokens: number;
  cache_read_tokens: number;
  thinking_tokens: number;
  total_tokens: number;
}

export function rawAntigravityUsageFromRecord(usage: Record<string, unknown> | undefined): RawAntigravityUsage | undefined {
  if (!usage) return undefined;
  const count = (value: unknown): number =>
    typeof value === "number" && Number.isFinite(value) && value >= 0 ? Math.floor(value) : 0;
  const raw: RawAntigravityUsage = {
    input_tokens: count(usage.input_tokens),
    output_tokens: count(usage.output_tokens),
    cache_read_tokens:
      count(usage.cache_read_tokens)
      || count(usage.cache_read_input_tokens)
      || count(usage.cached_tokens),
    thinking_tokens: count(usage.thinking_tokens),
    total_tokens: count(usage.total_tokens),
  };
  if (
    raw.input_tokens === 0
    && raw.output_tokens === 0
    && raw.cache_read_tokens === 0
    && raw.thinking_tokens === 0
    && raw.total_tokens === 0
  ) {
    return undefined;
  }
  return raw;
}

export function addRawAntigravityUsage(
  a: RawAntigravityUsage | undefined,
  b: RawAntigravityUsage | undefined,
): RawAntigravityUsage | undefined {
  if (!a) return b ? { ...b } : undefined;
  if (!b) return { ...a };
  return {
    input_tokens: a.input_tokens + b.input_tokens,
    output_tokens: a.output_tokens + b.output_tokens,
    cache_read_tokens: a.cache_read_tokens + b.cache_read_tokens,
    thinking_tokens: a.thinking_tokens + b.thinking_tokens,
    total_tokens: a.total_tokens + b.total_tokens,
  };
}

export function subtractRawAntigravityUsage(
  cumulative: RawAntigravityUsage,
  baseline: RawAntigravityUsage | undefined,
): RawAntigravityUsage {
  if (!baseline) return { ...cumulative };
  return {
    input_tokens: Math.max(0, cumulative.input_tokens - baseline.input_tokens),
    output_tokens: Math.max(0, cumulative.output_tokens - baseline.output_tokens),
    cache_read_tokens: Math.max(0, cumulative.cache_read_tokens - baseline.cache_read_tokens),
    thinking_tokens: Math.max(0, cumulative.thinking_tokens - baseline.thinking_tokens),
    total_tokens: Math.max(0, cumulative.total_tokens - baseline.total_tokens),
  };
}

