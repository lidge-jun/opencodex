export function flushAntigravityBridgedToolCalls(
  state: AntigravityStreamState,
  capturedMcpCalls?: ReadonlyArray<{ seq?: number; name: string; arguments: Record<string, unknown> }>,
): AdapterEvent[] {
  const pendingList = state.pendingBridgedToolCalls.splice(0);
  if (pendingList.length === 0) return [];
  const used = new Set<number>();
  const events: AdapterEvent[] = [];
  for (const pending of pendingList) {
    let argumentsJson = pending.fallbackArgumentsJson;
    let seq: number | undefined;
    if (capturedMcpCalls) {
      const idx = capturedMcpCalls.findIndex((item, i) => !used.has(i) && item.name === pending.mcpAlias);
      if (idx >= 0) {
        used.add(idx);
        seq = capturedMcpCalls[idx]!.seq;
        argumentsJson = JSON.stringify(capturedMcpCalls[idx]!.arguments);
      }
    }
    if (state.translatorBudget && pending.chargedArgsLeaseId) {
      const extraBytes = Buffer.byteLength(argumentsJson) - pending.chargedArgsBytes;
      if (extraBytes > 0) {
        state.translatorBudget.chargeRetained(extraBytes, {
          kind: "tool_args",
          callId: pending.chargedArgsLeaseId,
        });
      }
    }
    state.flushedToolCalls.push({
      seq,
      callId: pending.callId,
      mcpAlias: pending.mcpAlias,
      wireName: pending.wireName,
      argumentsJson,
    });
    events.push(
      { type: "tool_call_start", id: pending.callId, name: pending.wireName },
      { type: "tool_call_delta", arguments: argumentsJson },
      { type: "tool_call_end" },
    );
  }
  return events;
}

export function releaseAntigravityToolBudgets(state: AntigravityStreamState): void {
  const budget = state.translatorBudget;
  if (!budget) return;
  for (const leaseId of state.budgetCallIds.splice(0)) {
    budget.closeCall(leaseId);
  }
}

export function classifyAntigravityCliError(
  detail: string,
  usage?: OcxUsage,
): Extract<AdapterEvent, { type: "error" }> {
  const trimmed = detail.trim() || "Antigravity CLI ended the turn with an execution error.";
  const isAuth =
    /\bnot (?:logged|signed) in\b|\bsign[\s-]?in\b|\blogin required\b|\bunauthenticated\b|\bauthentication (?:failed|error|required)\b|\binvalid credentials\b|please run [`'"]?agy\b/i.test(
      trimmed,
    );
  if (isAuth) {
    return {
      type: "error",
      message:
        "Antigravity CLI is not signed in, so this subscription provider has no Google account to spend. "
        + "Run `agy` once and sign in with your Google account, then retry. "
        + `CLI reported: ${trimmed}`,
      status: 401,
      errorType: "authentication_error",
      code: "antigravity_cli_not_logged_in",
      retryable: false,
      ...(usage ? { usage } : {}),
    };
  }
  const isQuota = /insufficient[_\s-]quota|quota exceeded|credit usage limit|usage limit reached|exhausted your/i.test(trimmed);
  if (isQuota) {
    return {
      type: "error",
      message: trimmed,
      status: 429,
      errorType: "insufficient_quota",
      code: "insufficient_quota",
      retryable: false,
      ...(usage ? { usage } : {}),
    };
  }
  const isRateLimit = /rate[_\s-]limit|too many requests|resource_exhausted|\b429\b/i.test(trimmed);
  if (isRateLimit) {
    return {
      type: "error",
      message: trimmed,
      status: 429,
      errorType: "rate_limit_error",
      code: "rate_limit_exceeded",
      retryable: true,
      ...(usage ? { usage } : {}),
    };
  }
  const isModelNotFound = /model (?:is )?(?:not found|unavailable|unsupported)|unknown model|invalid model/i.test(trimmed);
  if (isModelNotFound) {
    return {
      type: "error",
      message: trimmed,
      status: 400,
      errorType: "invalid_request_error",
      code: "model_not_found",
      retryable: false,
      ...(usage ? { usage } : {}),
    };
  }
  const isInvalidArgument = /\binvalid_argument\b|\(code 400\)|\bstatus[:\s]+400\b/i.test(trimmed);
  if (isInvalidArgument) {
    return {
      type: "error",
      message: trimmed,
      status: 400,
      errorType: "invalid_request_error",
      code: "invalid_request_error",
      retryable: false,
      terminalRefusal: true,
      ...(usage ? { usage } : {}),
    };
  }
  const isTransientTransport = /\b(?:eof|etimedout|econnreset|econnrefused|service unavailable|bad gateway|gateway timeout|connection reset|deadline exceeded|temporarily unavailable)\b/i.test(trimmed);
  return {
    type: "error",
    message: trimmed,
    status: 502,
    errorType: "upstream_error",
    code: "upstream_error",
    retryable: isTransientTransport,
    ...(usage ? { usage } : {}),
  };
}

function isAllowedStagedImageToolStep(
  rawToolName: string,
  parameters: Record<string, unknown> | undefined,
  state: AntigravityStreamState,
): boolean {
  if (rawToolName !== "read_file" && rawToolName !== "view_file") return false;
  return isAllowedAntigravityStagedImageReadArgs(parameters, {
    imagePaths: state.stagedImagePaths,
    turnDir: state.turnDir,
    platform: state.platform,
  });
}

function isAtLeastRawAntigravityUsage(
  current: RawAntigravityUsage,
  baseline: RawAntigravityUsage,
): boolean {
  return current.input_tokens >= baseline.input_tokens
    && current.output_tokens >= baseline.output_tokens
    && current.cache_read_tokens >= baseline.cache_read_tokens
    && current.thinking_tokens >= baseline.thinking_tokens
    && current.total_tokens >= baseline.total_tokens;
}

function isTrackedFakeToolName(name: string, toolBridge?: AntigravityCliToolBridge): boolean {
  if (!name) return false;
  if (name.startsWith(ANTIGRAVITY_MCP_TOOL_PREFIX)) return true;
  if (name === "view_file" || name === "read_file") return true;
  if (!toolBridge) return false;
  if (toolBridge.emittedNameMap.has(name)) return true;
  for (const wireName of toolBridge.emittedNameMap.values()) {
    if (wireName === name) return true;
  }
  return false;
}

function stripLeadingAssistantPrefixChunk(chunk: string, state: AntigravityStreamState): string {
  if (state.leadingPrefixResolved) return chunk;
  const buf = state.leadingPrefixBuffer + chunk;
  state.leadingPrefixBuffer = "";
  let wsEnd = 0;
  while (wsEnd < buf.length && /\s/.test(buf[wsEnd]!)) wsEnd++;
  if (Buffer.byteLength(buf.slice(0, wsEnd), "utf8") > MAX_LEADING_PREFIX_WHITESPACE_BYTES) {
    state.leadingPrefixResolved = true;
    return buf;
  }
  if (wsEnd === buf.length) {
    state.leadingPrefixBuffer = buf;
    return "";
  }
  const rest = buf.slice(wsEnd);
  const upper = rest.slice(0, LEADING_ASSISTANT_PREFIX.length).toUpperCase();
  if (rest.length < LEADING_ASSISTANT_PREFIX.length) {
    if (LEADING_ASSISTANT_PREFIX.startsWith(upper)) {
      state.leadingPrefixBuffer = buf;
      return "";
    }
    state.leadingPrefixResolved = true;
    return buf;
  }
  if (upper !== LEADING_ASSISTANT_PREFIX) {
    state.leadingPrefixResolved = true;
    return buf;
  }
  const afterColon = rest.slice(LEADING_ASSISTANT_PREFIX.length);
  let pos = 0;
  while (pos < afterColon.length && (afterColon[pos] === " " || afterColon[pos] === "\t")) pos++;
  if (pos === afterColon.length) {
    if (Buffer.byteLength(afterColon, "utf8") > 64) {
      state.leadingPrefixResolved = true;
      return afterColon;
    }
    state.leadingPrefixBuffer = buf;
    return "";
  }
  if (afterColon[pos] === "\r") {
    pos++;
    if (pos === afterColon.length) {
      state.leadingPrefixBuffer = buf;
      return "";
    }
  }
  if (afterColon[pos] === "\n") pos++;
  state.leadingPrefixResolved = true;
  return afterColon.slice(pos);
}

function filterFakeToolCallsChunk(
  chunk: string,
  state: AntigravityStreamState,
  toolBridge?: AntigravityCliToolBridge,
): string {
  if (state.capturedToolCalls > 0) {
    const flushed = state.fakeToolProbeBuffer + chunk;
    state.fakeToolProbeBuffer = "";
    return flushed;
  }
  if (!chunk && !state.fakeToolProbeBuffer) return "";
  const buf = state.fakeToolProbeBuffer + chunk;
  state.fakeToolProbeBuffer = "";
  let out = "";
  let i = 0;
  while (i < buf.length) {
    const bracketIdx = buf.indexOf("[", i);
    if (bracketIdx < 0) {
      out += buf.slice(i);
      break;
    }
    if (bracketIdx > i) {
      out += buf.slice(i, bracketIdx);
      i = bracketIdx;
    }
    const tail = buf.slice(i);
    if (tail.length < FAKE_TOOL_MARKER.length) {
      if (FAKE_TOOL_MARKER.startsWith(tail)) {
        state.fakeToolProbeBuffer = tail;
        break;
      }
      out += "[";
      i += 1;
      continue;
    }
    if (!tail.startsWith(FAKE_TOOL_MARKER)) {
      out += "[";
      i += 1;
      continue;
    }
    let delimIdx = -1;
    for (let j = FAKE_TOOL_MARKER.length; j < tail.length; j++) {
      const ch = tail[j]!;
      if (ch === "(" || ch === "]" || ch === " " || ch === "\t" || ch === "\r" || ch === "\n") {
        delimIdx = j;
        break;
      }
    }
    if (delimIdx < 0) {
      if (Buffer.byteLength(tail, "utf8") < MAX_FAKE_TOOL_PROBE_BYTES) {
        state.fakeToolProbeBuffer = tail;
        break;
      }
      out += tail.slice(0, FAKE_TOOL_MARKER.length);
      i += FAKE_TOOL_MARKER.length;
      continue;
    }
    const candidateName = tail.slice(FAKE_TOOL_MARKER.length, delimIdx);
    if (isTrackedFakeToolName(candidateName, toolBridge)) {
      throw new AntigravityTerminalRefusalProtocolError(
        `Antigravity CLI emitted forged text tool call (${candidateName}) instead of invoking a structured MCP tool.`,
      );
    }
    out += tail.slice(0, FAKE_TOOL_MARKER.length);
    i += FAKE_TOOL_MARKER.length;
  }
  return out;
}

function processAssistantTextChunk(
  chunk: string,
  state: AntigravityStreamState,
  toolBridge?: AntigravityCliToolBridge,
): string {
  const afterLead = stripLeadingAssistantPrefixChunk(chunk, state);
  if (!afterLead) return "";
  return filterFakeToolCallsChunk(afterLead, state, toolBridge);
}

function flushAssistantTextBuffers(
  state: AntigravityStreamState,
  toolBridge?: AntigravityCliToolBridge,
): string {
  let out = "";
  if (!state.leadingPrefixResolved) {
    state.leadingPrefixResolved = true;
    const pendingLead = state.leadingPrefixBuffer;
    state.leadingPrefixBuffer = "";
    if (pendingLead && !/^\s*ASSISTANT:[ \t]*\r?\n?$/i.test(pendingLead)) {
      out += filterFakeToolCallsChunk(pendingLead, state, toolBridge);
    }
  }
  if (state.fakeToolProbeBuffer) {
    const pendingProbe = state.fakeToolProbeBuffer;
    state.fakeToolProbeBuffer = "";
    if (state.capturedToolCalls === 0 && pendingProbe.startsWith(FAKE_TOOL_MARKER)) {
      const candidateName = pendingProbe.slice(FAKE_TOOL_MARKER.length);
      if (isTrackedFakeToolName(candidateName, toolBridge)) {
        throw new AntigravityTerminalRefusalProtocolError(
          `Antigravity CLI emitted forged text tool call (${candidateName}) instead of invoking a structured MCP tool.`,
        );
      }
    }
    out += pendingProbe;
  }
  return out;
}

function emitFilteredAssistantText(
  text: string,
  state: AntigravityStreamState,
  events: AdapterEvent[],
): void {
  if (!text) return;
  const needsSeparator = state.awaitingPostToolTextSeparator
    && state.sawPartialText
    && !state.lastTextEndedWithNewline
    && !state.suppressStepSeparator
    && !text.startsWith("\n");
  state.awaitingPostToolTextSeparator = false;
  state.sawPartialText = true;
  const emittedText = needsSeparator ? `\n\n${text}` : text;
  state.lastTextEndedWithNewline = emittedText.endsWith("\n");
  state.emittedAssistantText += emittedText;
  events.push({ type: "text_delta", text: emittedText });
}

/**
 * Map one `agy --output-format stream-json` frame to zero or more OpenCodex `AdapterEvent`s.
 */
export function mapAntigravityStreamFrame(
  frame: StreamMessage,
  state: AntigravityStreamState,
  toolBridge?: AntigravityCliToolBridge,
): AdapterEvent[] {
  const eventKind = asString(frame.event);
  const events: AdapterEvent[] = [];
  const stepForSummary = eventKind === "step_update" ? asRecord(frame.step_update) : undefined;
  const resultForSummary = eventKind === "result" ? (asRecord(frame.result) ?? frame) : undefined;
  const summaryStepType = stepForSummary ? asString(stepForSummary.step_type) : undefined;
  const summaryState = stepForSummary
    ? asString(stepForSummary.state)
    : resultForSummary
      ? asString(resultForSummary.status)
      : undefined;
  state.recentFrames.push({
    type: eventKind ?? asString(frame.type) ?? "unknown",
    ...(summaryStepType ? { stepType: summaryStepType } : {}),
    ...(summaryState ? { state: summaryState } : {}),
  });
  if (state.recentFrames.length > 5) state.recentFrames.shift();

  const frameConvId = asString(frame.conversation_id);
  if (frameConvId && ANTIGRAVITY_CONVERSATION_UUID_RE.test(frameConvId)) {
    state.conversationId ??= frameConvId;
  }

  if (eventKind === "init") {
    state.sawInit = true;
    const initRecord = asRecord(frame.init);
    if (asString(initRecord?.permission_mode) === "always-proceed") {
      state.initError = "Antigravity CLI started in always-proceed permission mode, violating turn isolation.";
      return events;
    }
    const initAgent = asString(initRecord?.agent);
    if (initAgent && initAgent !== ANTIGRAVITY_BRIDGE_AGENT_NAME) {
      state.initError = `Antigravity CLI started with unexpected agent "${initAgent}" instead of ${ANTIGRAVITY_BRIDGE_AGENT_NAME}.`;
      return events;
    }
    if (toolBridge) {
      const listedTools = Array.isArray(initRecord?.tools)
        ? new Set(initRecord.tools.filter((item): item is string => typeof item === "string"))
        : undefined;
      if (!listedTools) {
        state.initError = "Antigravity CLI init frame did not report its active tool list for the isolated MCP bridge.";
        return events;
      }
      // Verified on live `agy 1.5.8`: `init` is emitted at stream start before MCP servers connect,
      // so `init.tools` lists built-in Cortex tools (including `call_mcp_tool`) rather than `mcp_*`.
      const hasMcpRuntime = listedTools.has("call_mcp_tool");
      const hasAllEagerTools = [...toolBridge.emittedNameMap.keys()].every(name => listedTools.has(name));
      if (!hasMcpRuntime && !hasAllEagerTools) {
        state.initError = "Antigravity CLI init frame did not enable MCP tool dispatch for the isolated tool bridge.";
        return events;
      }
    }
    return events;
  }

  if (eventKind === "step_update") {
    const step = asRecord(frame.step_update);
    if (!step) return events;
    const rawStepUsage = rawAntigravityUsageFromRecord(asRecord(step.usage));
    if (rawStepUsage) {
      const usageKey = typeof step.step_index === "number" && Number.isInteger(step.step_index) && step.step_index >= 0
        ? step.step_index
        : -1;
      state.stepRawUsages.set(usageKey, rawStepUsage);
      let summed: RawAntigravityUsage | undefined;
      for (const entry of state.stepRawUsages.values()) {
        summed = addRawAntigravityUsage(summed, entry);
      }
      state.partialUsage = usageFromAntigravityRecord(summed as unknown as Record<string, unknown>)
        ?? state.partialUsage;
    }

    const stepType = asString(step.step_type);
    if (stepType === "agent_response") {
      const stepIndex = typeof step.step_index === "number" && Number.isInteger(step.step_index) && step.step_index >= 0
        ? step.step_index
        : undefined;
      if (stepIndex !== undefined && state.lastTextStepIndex !== undefined && stepIndex !== state.lastTextStepIndex) {
        emitFilteredAssistantText(flushAssistantTextBuffers(state, toolBridge), state, events);
        state.sawLatestStepPartialText = false;
        if (state.sawPartialText) state.awaitingPostToolTextSeparator = true;
      }
      const thinkingDelta = asString(step.thinking_delta);
      if (thinkingDelta) {
        events.push({ type: "thinking_delta", thinking: thinkingDelta });
      }
      const textDelta = asString(step.text_delta);
      if (textDelta) {
        if (stepIndex !== undefined) state.lastTextStepIndex = stepIndex;
        state.sawLatestStepPartialText = true;
        state.rawStreamedText += textDelta;
        const filtered = processAssistantTextChunk(textDelta, state, toolBridge);
        emitFilteredAssistantText(filtered, state, events);
      }
      return events;
    }

    if (stepType === "tool") {
      if (toolBridge && !state.sawInit) {
        state.missingInitBeforeTool = true;
        return events;
      }
      emitFilteredAssistantText(flushAssistantTextBuffers(state, toolBridge), state, events);
      const stepIndex = typeof step.step_index === "number" && Number.isInteger(step.step_index) && step.step_index >= 0
        ? step.step_index
        : undefined;
      const stepState = asString(step.state)?.toUpperCase();
      const toolInfo = asRecord(step.tool_info);
      if (stepState === "ERROR") {
        const errMsg = asString(asRecord(toolInfo?.error)?.message) ?? asString(step.error) ?? "";
        if (/PreToolUse payload exceeded the byte ceiling/i.test(errMsg)) {
          state.rawUpstreamError = errMsg;
          if (stepIndex !== undefined) {
            state.pendingUndeclaredTools.delete(stepIndex);
            state.seenStagedImageStepIndices.delete(stepIndex);
            const pendingIdx = state.pendingBridgedToolCalls.findIndex(item => item.stepIndex === stepIndex);
            if (pendingIdx >= 0) {
              const [removed] = state.pendingBridgedToolCalls.splice(pendingIdx, 1);
              state.capturedToolCalls = Math.max(0, state.capturedToolCalls - 1);
              if (state.translatorBudget && removed?.chargedLeaseIds?.length) {
                const released = new Set(removed.chargedLeaseIds);
                for (const leaseId of released) {
                  state.translatorBudget.closeCall(leaseId);
                }
                state.budgetCallIds = state.budgetCallIds.filter(id => !released.has(id));
              }
            }
          }
          throw new AntigravityTerminalRefusalProtocolError(`Antigravity CLI isolated MCP tool call failed: ${errMsg}`);
        }
      }
      const rawToolName = asString(toolInfo?.name) ?? asString(step.tool_name) ?? "";
      if (stepIndex !== undefined && state.seenToolStepIndices.has(stepIndex)) {
        if (stepState === "ERROR") {
          const pendingIdx = state.pendingBridgedToolCalls.findIndex(item => item.stepIndex === stepIndex);
          if (pendingIdx >= 0) {
            const [removed] = state.pendingBridgedToolCalls.splice(pendingIdx, 1);
            state.capturedToolCalls = Math.max(0, state.capturedToolCalls - 1);
            if (state.translatorBudget && removed?.chargedLeaseIds?.length) {
              const released = new Set(removed.chargedLeaseIds);
              for (const leaseId of released) {
                state.translatorBudget.closeCall(leaseId);
              }
              state.budgetCallIds = state.budgetCallIds.filter(id => !released.has(id));
            }
            state.sawLatestStepPartialText = false;
            if (state.sawPartialText) state.awaitingPostToolTextSeparator = true;
            const errInfo = asRecord(toolInfo?.error);
            const errMsg = asString(errInfo?.message)
              ?? asString(step.error)
              ?? "isolated MCP tool step errored";
            const safeTool = redactAntigravityLogText(rawToolName || removed?.mcpAlias || "<unknown>");
            const safeErr = capUtf8Bytes(redactAntigravityLogText(errMsg), 512);
            const reqTag = state.requestId ? ` requestId=${state.requestId}` : "";
            console.debug(
              `[antigravity-cli] bridged tool step=${stepIndex} tool=${safeTool}${reqTag} errored; released pending call: ${safeErr}`,
            );
          }
        }
        return events;
      }
      const parameters = toolInfo?.parameters === undefined ? undefined : asRecord(toolInfo.parameters);

      const isStagedImageStep = parameters !== undefined
        ? isAllowedStagedImageToolStep(rawToolName, parameters, state)
        : (stepIndex !== undefined
          && state.seenStagedImageStepIndices.has(stepIndex)
          && (rawToolName === "" || rawToolName === "read_file" || rawToolName === "view_file"));
      if (isStagedImageStep) {
        if (stepIndex !== undefined) state.seenStagedImageStepIndices.add(stepIndex);
        state.sawLatestStepPartialText = false;
        if (state.sawPartialText) state.awaitingPostToolTextSeparator = true;
        return events;
      }
      if (stepIndex !== undefined) state.seenStagedImageStepIndices.delete(stepIndex);

      const wireName = toolBridge ? toolBridge.emittedNameMap.get(rawToolName) : undefined;
      if (!toolBridge || !wireName) {
        const label = rawToolName || "<unknown>";
        // Live `agy 1.5.8` emits `state: "ACTIVE"` BEFORE running `PreToolUse`, then ~100ms later
        // emits `state: "ERROR"` with `"tool call denied by pre-tool hook: ..."` so the model can
        // self-correct. Hold `ACTIVE` undeclared steps in `pendingUndeclaredTools` until denied,
        // and fail closed immediately if any undeclared tool executes (`DONE`), errors without a
        // pre-tool denial, or omits `step_index`.
        if (stepIndex !== undefined && stepState === "ACTIVE") {
          state.pendingUndeclaredTools.set(stepIndex, label);
          return events;
        }
        if (stepIndex !== undefined && stepState === "ERROR") {
          const errInfo = asRecord(toolInfo?.error);
          const errMsg = asString(errInfo?.message) ?? asString(step.error) ?? "";
          if (ANTIGRAVITY_PRETOOL_DENIAL_RE.test(errMsg)) {
            state.pendingUndeclaredTools.delete(stepIndex);
            state.sawLatestStepPartialText = false;
            if (state.sawPartialText) state.awaitingPostToolTextSeparator = true;
            return events;
          }
        }
        if (stepIndex !== undefined) state.pendingUndeclaredTools.delete(stepIndex);
        state.undeclaredToolName = label;
        return events;
      }

      if (stepState === "ERROR") {
        const errInfo = asRecord(toolInfo?.error);
        const errMsg = asString(errInfo?.message) ?? "isolated MCP tool step failed before capture parked";
        state.rawUpstreamError = errMsg;
        const message = `Antigravity CLI isolated MCP tool call failed: ${errMsg}`;
        if (ANTIGRAVITY_PRETOOL_DENIAL_RE.test(errMsg) || /PreToolUse payload exceeded the byte ceiling/i.test(errMsg)) {
          throw new AntigravityTerminalRefusalProtocolError(message);
        }
        throw new CodingAgentProtocolError(message);
      }
      const callParams = toolInfo?.parameters === undefined ? {} : parameters;
      if (!callParams) {
        throw new AntigravityTerminalRefusalProtocolError("Antigravity CLI returned a tool call with non-object parameters.");
      }
      if (state.capturedToolCalls >= toolBridge.maxTurnToolCalls) {
        state.toolCallLimitExceeded = true;
        return events;
      }
      const argumentsJson = JSON.stringify(callParams);
      const argsBytes = Buffer.byteLength(argumentsJson);
      const callId = `call_${stepIndex ?? state.capturedToolCalls}_${state.callIdSuffix}`;
      let chargedArgsLeaseId: string | undefined;
      const openedLeaseIds: string[] = [];
      if (state.translatorBudget) {
        try {
          for (const [idx, bytes] of [Buffer.byteLength(callId), Buffer.byteLength(wireName) + argsBytes].entries()) {
            const leaseId = `antigravity-cli-tool:${++nextBudgetLeaseOrdinal}`;
            state.translatorBudget.openCall(leaseId);
            openedLeaseIds.push(leaseId);
            if (idx === 1) chargedArgsLeaseId = leaseId;
            state.translatorBudget.chargeRetained(bytes, { kind: "tool_args", callId: leaseId });
          }
          state.budgetCallIds.push(...openedLeaseIds);
        } catch (err) {
          for (const leaseId of openedLeaseIds) state.translatorBudget.closeCall(leaseId);
          throw err;
        }
      }
      if (stepIndex !== undefined) state.seenToolStepIndices.add(stepIndex);
      state.capturedToolCalls += 1;
      if (state.deferToolCallEmission) {
        // `agy 1.5.8` truncates string fields >512 chars with `…` in `step_update.tool_info.parameters`.
        // Defer emission until coalesce flush so live runs substitute untruncated MCP JSON-RPC arguments.
        const mcpAlias = rawToolName.startsWith(ANTIGRAVITY_MCP_TOOL_PREFIX)
          ? rawToolName.slice(ANTIGRAVITY_MCP_TOOL_PREFIX.length)
          : rawToolName;
        state.pendingBridgedToolCalls.push({
          stepIndex,
          callId,
          mcpAlias,
          wireName,
          fallbackArgumentsJson: argumentsJson,
          chargedArgsLeaseId,
          chargedArgsBytes: argsBytes,
          chargedLeaseIds: openedLeaseIds,
        });
        return events;
      }
      events.push(
        { type: "tool_call_start", id: callId, name: wireName },
        { type: "tool_call_delta", arguments: argumentsJson },
        { type: "tool_call_end" },
      );
      return events;
    }

    return events;
  }

  if (eventKind === "result") {
    if (state.pendingUndeclaredTools.size > 0) {
      state.undeclaredToolName = state.pendingUndeclaredTools.values().next().value;
      return events;
    }
    const result = asRecord(frame.result) ?? frame;
    const rawResult = rawAntigravityUsageFromRecord(asRecord(result.usage));
    if (rawResult) state.resultRawUsage = rawResult;
    if (rawResult && state.usageBaseline && isAtLeastRawAntigravityUsage(rawResult, state.usageBaseline)) {
      const deltaRaw = subtractRawAntigravityUsage(rawResult, state.usageBaseline);
      const deltaUsage = usageFromAntigravityRecord(deltaRaw as unknown as Record<string, unknown>);
      if (deltaUsage) state.partialUsage = mergeAntigravityUsage(state.partialUsage, deltaUsage);
    } else {
      const resultUsage = usageFromAntigravityRecord(asRecord(result.usage));
      if (resultUsage) state.partialUsage = mergeAntigravityUsage(state.partialUsage, resultUsage);
    }
    const usage = state.partialUsage;

    const status = asString(result.status)?.toUpperCase();
    const errorField = result.error;
    const errorRecord = asRecord(errorField);
    const errorString = asString(errorField) ?? asString(errorRecord?.message);
    const isError = (status !== undefined && status !== "SUCCESS")
      || result.is_error === true
      || Boolean(errorString);

    if (isError) {
      const detail = errorString
        || asString(result.message)
        || asString(result.response)
        || (status ? `Antigravity CLI ended with status ${status}.` : "Antigravity CLI ended the turn with an execution error.");
      const rawErrorText = typeof errorField === "string"
        ? errorField
        : errorField !== undefined
          ? JSON.stringify(errorField)
          : detail;
      state.rawUpstreamError = rawErrorText;
      events.push(classifyAntigravityCliError(detail, usage));
      return events;
    }

    state.sawTerminalResult = true;
    const willFailClosedOnDone = Boolean(
      toolBridge && (
        !state.sawInit
        || (toolBridge.requireToolCall && state.capturedToolCalls === 0)
        || state.capturedToolCalls > 0
      ),
    );
    const fullResponse = asString(result.response);
    const responseText = !state.sawLatestStepPartialText && fullResponse
      ? (state.rawStreamedText && fullResponse.startsWith(state.rawStreamedText)
          ? fullResponse.slice(state.rawStreamedText.length)
          : fullResponse)
      : "";
    if (!willFailClosedOnDone) {
      const filteredTail = responseText
        ? processAssistantTextChunk(responseText, state, toolBridge)
        : "";
      const flushedTail = flushAssistantTextBuffers(state, toolBridge);
      emitFilteredAssistantText(filteredTail + flushedTail, state, events);
    } else if (state.capturedToolCalls === 0) {
      if (responseText) processAssistantTextChunk(responseText, state, toolBridge);
      flushAssistantTextBuffers(state, toolBridge);
    }
    events.push({
      type: "done",
      stopReason: "stop",
      ...(usage ? { usage } : {}),
    });
    return events;
  }

  return events;
}
